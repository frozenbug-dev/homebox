export type IconName = (typeof availableIcons)[number]["name"];

export const defaultIcon = Tag;

// eslint-disable-next-line @typescript-eslint/no-explicit-any
export function getIconComponent(iconName: string | undefined): any {
  if (!iconName) {
    return defaultIcon;
  }
  const icon = availableIcons.find(i => i.name === iconName);
  return icon ? icon.component : defaultIcon;
}

export function iconLabel(name: string): string {
  return name
    .replace(/-outline$/, "")
    .replace(/-\d+$/, "")
    .replace(/-/g, " ");
}

/** Filters icons by name or keyword; every whitespace-separated term must match. */
export function searchIcons(query: string) {
  const terms = query.trim().toLowerCase().split(/\s+/).filter(Boolean);
  if (!terms.length) return availableIcons;
  return availableIcons.filter(i => {
    const hay = `${iconLabel(i.name)} ${i.keywords}`;
    return terms.every(t => hay.includes(t));
  });
}
